//指针数据类型：跟指向的空间中数据的类型是保持一致的
#include<stdio.h>

int main()
{
    //定义变量
    int a=10;
    int b=20;
    //定义一级指针
    int* p=&a;
    //定义二级指针
    int* *pp=&p;
    //数据类型（int*) (*)定义指针的特殊标志
    //作用一：利用二级指针修改一级指针里面的内存地址
    * pp=&b;

    
    //输出打印
    printf("%p\n",&a);
    printf("%p\n",&b);
    printf("%p\n",p);
    //作用二：利用二级指针获取到变量中记录的数据
    printf("%d\n",**pp);//*pp 获取到一级指针的内存地址 
    //**pp通过一级指针的内存地址获取到变量里面的数据

    return 0;
}